// Generates the compact OpenSkyLab specification v0.3 table embedded in metadata-reader.html.
// Reads the field list (block, field, module, level, source, unit), the mapping CSV (ISO 19115, DataCite, STAC) and the JSON schema (type of each field).
// Usage: node metadata-reader_gen.js <dir with the v0.3 data files> > metadata-reader_osl.js
const fs = require("fs"), path = require("path");
const F = process.argv[2] || path.join(__dirname, "data");
function csv(text) {
  const rows = []; let row = [], cell = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"') { if (text[i + 1] === '"') { cell += '"'; i++; } else q = false; } else cell += c; }
    else if (c === '"') q = true; else if (c === ",") { row.push(cell); cell = ""; } else if (c === "\n" || c === "\r") { if (c === "\r" && text[i + 1] === "\n") i++; row.push(cell); rows.push(row); row = []; cell = ""; } else cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows.filter(r => r.length > 1);
}
const V = "0.3";
const map = csv(fs.readFileSync(path.join(F, "openskylab_metadata_mapping_v" + V + ".csv"), "utf8"));
const head = map.shift();
const schema = JSON.parse(fs.readFileSync(path.join(F, "openskylab_metadata_schema_v" + V + ".json"), "utf8"));
const fields = JSON.parse(fs.readFileSync(path.join(F, "openskylab_metadata_fields_v" + V + ".json"), "utf8")).fields;
const page = {};
for (const f of fields) page[f.block + "." + f.field] = { unit: f.unit || "", source: f.source || "", module: f.module };
// schema types
const P = schema.properties, blockPath = { dataset: [P.dataset], mission: [P.missions.items], sensor: [P.sensors.items], geometry: [P.sensors.items.properties.geometry],
  multispectral: [P.sensors.items.properties.multispectral], thermal: [P.sensors.items.properties.thermal], reference: [P.references.items], processing: [P.processing.items], product: [P.products.items], environment: [P.missions.items.properties.environment || {}] };
function stype(block, field) {
  for (const o of blockPath[block] || []) { const p = o && o.properties && o.properties[field]; if (p) { let t = p.type || (p.enum ? "enum" : p.$ref ? "ref" : p.oneOf ? "oneOf" : ""); if (Array.isArray(t)) t = t.join("|"); if (t === "array" && p.items && p.items.type) t = "array<" + p.items.type + ">"; return t; } }
  return "";
}
const out = []; let miss = 0; const sources = {};
for (const r of map) {
  const o = Object.fromEntries(head.map((h, i) => [h, r[i] || ""]));
  const pg = page[o.block + "." + o.field] || null; if (!pg) miss++;
  if (pg) sources[pg.source] = (sources[pg.source] || 0) + 1;
  out.push([o.block, o.field, o.level, o.iso_19115, o.stac, pg ? pg.source : "", pg ? pg.unit : "", stype(o.block, o.field), o.datacite_4, pg ? pg.module : o.module]);
}
process.stderr.write("rows " + out.length + ", without page row " + miss + "\nsources " + JSON.stringify(sources) + "\n");
const levels = {}; for (const r of out) levels[r[2]] = (levels[r[2]] || 0) + 1; process.stderr.write("levels " + JSON.stringify(levels) + "\n");
console.log("/* OpenSkyLab metadata specification v" + V + ", generated by metadata-reader_gen.js from openskylab_metadata_fields_v" + V + ".json, openskylab_metadata_mapping_v" + V + ".csv and openskylab_metadata_schema_v" + V + ".json */");
console.log("const OSL_STD = { version: \"" + V + "\", cols: [\"block\", \"field\", \"level\", \"iso_19115\", \"stac\", \"source\", \"unit\", \"type\", \"datacite_4\", \"module\"], rows: " + JSON.stringify(out) + " };");
